#!/bin/sh
# Regenerate config/includes.installer/usr/share/kubeos/localechooser-overrides.templates
#
# KubeOS rewrites two debconf templates that Debian's localechooser udeb ships:
#
#   localechooser/shortlist/en        the "shortlist" screen shown for English
#   localechooser/countrylist/Asia    the full continent list behind "other"
#
# Current edits, relative to what Debian ships:
#   localechooser/shortlist/en        - IL   + PS (Palestine)
#   localechooser/countrylist/Asia    - IL, and PS shortened from Debian's
#                                       formal "Palestine\, State of" to
#                                       "Palestine" (in every language where
#                                       the formal name is comma-separated)
#
# Why this is generated and not hand-edited: both templates are POSITIONAL.
# Choices-C, Choices, every translated Choices-<locale>.UTF-8 list and every
# Indices-<locale> display-order table are indexed by the same position, so
# deleting or inserting one country means rewriting all of them and
# renumbering every index. Two further traps live in that data: a country name
# may contain an ESCAPED comma ("Pal\xc3\xa4stina\, Staat"), so a plain ", " split
# invents an entry, and the lists are translated into ~75 locales, so they
# cannot be checked by eye.
#
# Usage:
#   tools/gen-localechooser-overrides.sh <localechooser.templates> [output]
#
# Where to get <localechooser.templates> — take it from the installer initrd the
# build actually used, so the source matches the udeb in the ISO:
#   xorriso -osirrox on -indev kubeos-0.1.0-alpha-amd64.hybrid.iso \
#     -extract /install/gtk/initrd.gz /tmp/gtk.gz
#   cd /tmp && gzip -dc gtk.gz | cpio -id --no-absolute-filenames \
#     var/lib/dpkg/info/localechooser.templates
#
# Re-run this whenever Debian updates localechooser. If the structure changed,
# the script fails loudly instead of producing a subtly broken list.

set -eu

src=${1:?usage: $0 <localechooser.templates> [output]}
out=${2:-config/includes.installer/usr/share/kubeos/localechooser-overrides.templates}

[ -r "$src" ] || { echo "E: cannot read $src" >&2; exit 1; }

tmp=$(mktemp) || exit 1
trap 'rm -f "$tmp"' EXIT

awk '
BEGIN {
	DROP = "IL"
	ADD_CODE = "PS"
	ADD_NAME = "Palestine"

	# Templates to rewrite. `add` is only set for the shortlist: the Asia list
	# already contains PS, and inserting into a template that has translated
	# name lists would mean inventing 75 translations.
	t_short = "localechooser/shortlist/en"
	t_asia  = "localechooser/countrylist/Asia"
	target[t_short] = 1
	target[t_asia] = 1
	add[t_short] = 1

	print "# Generated by tools/gen-localechooser-overrides.sh - do not edit."
	print "# Source: Debian localechooser.templates, with " DROP " (Israel) removed"
	print "# and " ADD_CODE " (" ADD_NAME ") added to the English shortlist."
	print ""
}

function fail(msg) {
	nlines = 0
	printf("E: %s: %s\n", tmpl, msg) > "/dev/stderr"
	failed = 1
	exit 1
}

function splitfield(line,   f) {
	f = line
	sub(/: .*/, "", f)
	return f
}

function valueof(line, f) {
	return substr(line, length(f) + 3)
}

# Debian escapes a comma that belongs to a country name ("Pal\xc3\xa4stina\, Staat"),
# so split on ", " only after masking those.
function mask(s) { gsub(/\\,/, "\001", s); return s }
function unmask(s) { gsub("\001", "\\,", s); return s }

function join(a, n, skip, extra,   j, s) {
	s = ""
	for (j = 1; j <= n; j++) {
		if (j == skip)
			continue
		s = (s == "") ? a[j] : s ", " a[j]
	}
	return unmask(s)
}

function count_choices_c(   i, f, a) {
	for (i = 1; i <= nlines; i++) {
		f = splitfield(lines[i])
		if (f == "Choices-C")
			return split(mask(valueof(lines[i], f)), a, /, /)
	}
	return 0
}

# Insert ADD_CODE/ADD_NAME at its alphabetical place, keeping "other" last.
function add_country(   i, j, f, a, n, ins, name_at, expected, s, have_code) {
	expected = count_choices_c()
	if (expected < 5)
		fail("Choices-C missing or too short - structure changed?")

	# Already there? Then this is a no-op (idempotent runs).
	for (i = 1; i <= nlines; i++) {
		f = splitfield(lines[i])
		if (f == "Choices-C") {
			n = split(mask(valueof(lines[i], f)), a, /, /)
			for (j = 1; j <= n; j++)
				if (a[j] == ADD_CODE)
					have_code = 1
		}
	}
	if (have_code)
		return

	# Position from the English name list.
	ins = 0
	for (i = 1; i <= nlines; i++) {
		f = splitfield(lines[i])
		if (f != "Choices")
			continue
		n = split(mask(valueof(lines[i], f)), a, /, /)
		name_at = i
		for (j = 1; j <= n; j++) {
			if (a[j] == "other" || tolower(unmask(a[j])) > tolower(ADD_NAME)) {
				ins = j
				break
			}
		}
		if (ins == 0)
			ins = n
	}
	if (ins == 0)
		fail("no Choices field to anchor the insertion")

	for (i = 1; i <= nlines; i++) {
		f = splitfield(lines[i])
		if (f == "Choices-C") {
			n = split(mask(valueof(lines[i], f)), a, /, /)
			if (n != expected)
				fail("Choices-C changed while editing")
			s = ""
			for (j = 1; j <= n; j++) {
				if (j == ins)
					s = (s == "") ? ADD_CODE : s ", " ADD_CODE
				s = (s == "") ? a[j] : s ", " a[j]
			}
			if (ins > n)
				s = s ", " ADD_CODE
			lines[i] = f ": " s
		} else if (f == "Choices") {
			n = split(mask(valueof(lines[i], f)), a, /, /)
			s = ""
			for (j = 1; j <= n; j++) {
				if (j == ins)
					s = (s == "") ? ADD_NAME : s ", " ADD_NAME
				s = (s == "") ? a[j] : s ", " a[j]
			}
			if (ins > n)
				s = s ", " ADD_NAME
			lines[i] = f ": " s
		} else if (f ~ /^Choices-/ || f ~ /^Indices/) {
			# A translated name list or an ordering table: inserting here
			# would need a translation respectively a renumbered permutation
			# that we cannot derive. Refuse instead of guessing.
			fail(f " exists, so " ADD_CODE " cannot be inserted safely")
		}
	}
}

# Remove DROP from every positional field of the stanza.
function drop_country(   i, j, f, a, n, pos, expected, s) {
	pos = 0
	expected = count_choices_c()
	if (expected < 5)
		fail("Choices-C missing or too short - structure changed?")

	for (i = 1; i <= nlines; i++) {
		f = splitfield(lines[i])
		if (f == "Choices-C") {
			n = split(mask(valueof(lines[i], f)), a, /, /)
			for (j = 1; j <= n; j++)
				if (a[j] == DROP)
					pos = j
		}
	}
	if (pos == 0)
		return          # already absent (idempotent runs)

	for (i = 1; i <= nlines; i++) {
		f = splitfield(lines[i])

		if (f ~ /^Choices/) {
			n = split(mask(valueof(lines[i], f)), a, /, /)
			if (n != expected)
				fail(f " has " n " entries, Choices-C has " expected \
				      " - structure changed, refusing to guess")
			lines[i] = f ": " join(a, n, pos)
		} else if (f ~ /^Indices/) {
			n = split(mask(valueof(lines[i], f)), a, /, /)
			if (n != expected)
				fail(f " has " n " entries, Choices-C has " expected)
			s = ""
			for (j = 1; j <= n; j++) {
				v = a[j] + 0
				if (v == pos)
					continue
				if (v > pos)
					v--
				if (v < 1 || v > expected - 1)
					fail(f " value " a[j] " out of range")
				s = (s == "") ? v : s ", " v
			}
			lines[i] = f ": " s
		}
	}
}

# Debian names PS formally: "Palestine\, State of", and the same pattern in the
# other languages that translate it ("Pal\xc3\xa4stina\, Staat", "Palestina\, Estado de").
# The escaped comma is the marker to cut at; languages whose formal name has no
# comma ("\xd8\xb4\xd9\x88\xd9\x84\xd8\xa9 \xd9\x81\xd9\x84\xd8\xb3\xd8\xb7\xd9\x8a\xd9\x86") are left alone rather
# than mangled.
function shorten_country(   i, j, f, a, n, pos, expected, s, cut, changed, untouched) {
	pos = 0
	expected = count_choices_c()
	if (expected < 5)
		fail("Choices-C missing or too short - structure changed?")

	for (i = 1; i <= nlines; i++) {
		f = splitfield(lines[i])
		if (f == "Choices-C") {
			n = split(mask(valueof(lines[i], f)), a, /, /)
			for (j = 1; j <= n; j++)
				if (a[j] == ADD_CODE)
					pos = j
		}
	}
	if (pos == 0)
		fail("country code " ADD_CODE " not found in Choices-C")

	changed = 0
	untouched = 0
	for (i = 1; i <= nlines; i++) {
		f = splitfield(lines[i])
		if (!(f ~ /^Choices/) || f == "Choices-C")
			continue
		n = split(mask(valueof(lines[i], f)), a, /, /)
		if (n != expected)
			fail(f " has " n " entries, Choices-C has " expected)
		if (index(a[pos], "\001") > 0) {
			cut = index(a[pos], "\001") - 1
			a[pos] = substr(a[pos], 1, cut)
			changed++
		} else {
			untouched++
		}
		lines[i] = f ": " join(a, n, 0)
	}
	printf("note: %s: shortened %d name lists, %d had no comma to cut at\n", \
	       tmpl, changed, untouched) > "/dev/stderr"
}

function flush(   i) {
	if (nlines == 0)
		return
	tmpl = lines[1]
	sub(/^Template: /, "", tmpl)
	if (!(tmpl in target)) {       # only the overridden templates are emitted
		nlines = 0
		return
	}
	if (tmpl in add)
		add_country()
	else
		shorten_country()
	drop_country()
	saw[tmpl] = 1
	for (i = 1; i <= nlines; i++)
		print lines[i]
	print ""
	nlines = 0
}

/^$/ { flush(); next }

{ lines[++nlines] = $0 }

END {
	if (failed)
		exit 1
	flush()
	if (!(t_short in saw)) {
		printf("E: template %s not found in the input\n", t_short) > "/dev/stderr"
		exit 1
	}
	if (!(t_asia in saw)) {
		printf("E: template %s not found in the input\n", t_asia) > "/dev/stderr"
		exit 1
	}
}
' "$src" > "$tmp" || exit 1

mv "$tmp" "$out"
trap - EXIT
echo "wrote $out ($(wc -c < "$out") bytes)"
